// G01 WorldGrowthController — multi-origin procedural world growth (pure data, no rendering; runs in Node).
//
// World = six City Cores + chunks grown one at a time from a Growth Frontier. Nothing is pre-allocated: the grid is
// a sparse map of integer cells (gx, gy) that grows in any direction.
//
// Reproducibility rules:
//   * A cell's terrain (landform, terrainSeed, variation) depends on worldSeed + position only (growthConfig.cellOf).
//   * A chunk's content depends on its cell + cityId only (single-chunk chain of 06.2, spatial ids of 07.1a), so the
//     order in which chunks are grown never changes an already generated chunk.
//   * Every random choice is a keyed hash of (worldSeed, position, step) — there is no shared random stream.
//   * Records are immutable once created; growth of other cities never edits them (first occupant keeps the cell).
//
// Per step: fair scheduler picks the city (lowest chunks / rate) → its frontier cells are scored on real terrain
// (probe = raw terrain + analysis + 02.6 match) → contested cells go to the rival with a clearly higher score →
// best cell becomes a chunk with parent = an adjacent chunk of the same city → terrain + network are generated and
// the new shared edges are measured (height step, water, road ports). The urban layer (blocks / parcels /
// buildings) is generated by the caller from the returned transient layers (render path).
import { computeMatchMetrics, matchCity } from '../seed-terrain/CityMatcher.js';
import { generateRawLayer, generateTerrainLayer, generateNetworkLayer } from '../world-grid/WorldGrid.js';
import { CITY_DNA } from '../seed-terrain/cityMatchRules.js';
import { TRANSITION } from '../seed-terrain/config.js';
import { CITY_GROWTH, CITY_ORDER, GROWTH_VERSION, RULES, cellKey, cellOf, normaliseParams, unit } from './growthConfig.js';

const now = () => (globalThis.performance ?? Date).now();
const NEIGHBOURS = [[1, 0, 'maxX', 'minX'], [-1, 0, 'minX', 'maxX'], [0, 1, 'maxZ', 'minZ'], [0, -1, 'minZ', 'maxZ']]; // dx, dy, side of A, side of B
const clamp01 = v => Math.min(1, Math.max(0, v));
const round = (v, d = 3) => +v.toFixed(d);
const sortCells = (a, b) => a.gy - b.gy || a.gx - b.gx;
const TRANSITION_WIDTH = TRANSITION.initial;

// world / slot objects accepted by the unchanged 06.2 layer functions.
const worldOf = cell => ({ variation: cell.variation, transitionWidth: TRANSITION_WIDTH });
const slotOf = (cell, cityId) => ({ chunkId: cell.chunkId, landform: cell.landform, terrainSeed: cell.terrainSeed, worldOrigin: cell.worldOrigin, cityId });

// Single-chunk chain for one cell: raw terrain → fields + analysis (the terrain layer) → optional network.
export function terrainOf(cell) {
  const world = worldOf(cell);
  const slot = slotOf(cell, null);
  const raw = generateRawLayer(world, slot);
  return generateTerrainLayer(world, slot, raw, { height: raw.chunk.height, waterSurface: raw.chunk.waterSurface }, `${cell.chunkId}|${cell.landform}|${cell.terrainSeed}|${cell.variation}`);
}
export const networkOf = (cell, cityId, terrain) => generateNetworkLayer(worldOf(cell), slotOf(cell, cityId), terrain);

// Edge profiles (every 2nd sample, 8 m) of height and wetness, for seam measurement without keeping the fields.
function edgeProfiles(fields) {
  const { segments, columns } = fields.grid;
  const pick = (index) => ({ h: round(fields.height[index], 2), w: fields.waterMask[index] ? 1 : 0 });
  const sides = { minX: [], maxX: [], minZ: [], maxZ: [] };
  for (let i = 0; i <= segments; i += 2) {
    sides.minX.push(pick(i * columns)); // col 0, row i (row runs along +z)
    sides.maxX.push(pick(i * columns + segments));
    sides.minZ.push(pick(i)); // row 0, col i (col runs along +x)
    sides.maxZ.push(pick(segments * columns + i));
  }
  return Object.fromEntries(Object.entries(sides).map(([side, list]) => [side, { h: list.map(p => p.h), w: list.map(p => p.w).join('') }]));
}

export class WorldGrowthController {
  constructor(params = {}) {
    this.params = normaliseParams(params);
    this.reset();
  }

  reset() {
    this.chunks = new Map(); // cellKey → immutable record
    this.edges = new Map(); // 'a|b' → shared edge report (created when the second chunk appears)
    this.history = []; // one entry per created chunk (cores included)
    this.issues = []; // suitability issues and stalls (never silently fixed)
    this.cores = []; // chunkIds of the six cores
    this.step = 0; // number of growth steps taken (cores are step 0)
    this.probes = new Map(); // cellKey → compact terrain probe (cache only, derivable)
    this.stats = { probes: 0, probeMs: 0, buildMs: 0 };
  }

  get worldSeed() { return this.params.worldSeed; }
  at(gx, gy) { return this.chunks.get(cellKey(gx, gy)) ?? null; }
  byId(chunkId) { return [...this.chunks.values()].find(r => r.chunkId === chunkId) ?? null; }
  countOf(cityId) { let n = 0; for (const r of this.chunks.values()) if (r.cityId === cityId) n += 1; return n; }

  // Compact terrain probe of a cell (real terrain + analysis + 02.6 fit for all six DNAs). City-neutral, cached.
  probe(gx, gy) {
    const key = cellKey(gx, gy);
    if (this.probes.has(key)) return this.probes.get(key);
    const started = now();
    const cell = cellOf(this.worldSeed, gx, gy);
    const terrain = terrainOf(cell);
    const match = matchCity(terrain.analysis);
    const m = computeMatchMetrics(terrain.analysis);
    const probe = {
      cell,
      waterFraction: round(m.waterFraction ?? 0), buildableFraction: round(m.buildableFraction ?? 0),
      largestBuildable: round(m.largestBuildableShare ?? 0), lowSlope: round(m.highSuitabilityShareOfLand ?? 0),
      autoTopId: match.selectedDNA.autoTopId,
      fit: Object.fromEntries(match.rankedCandidates.map(c => [c.id, { fitScore: c.fitScore, weakFit: c.weakFit, conflicts: c.conflicts.filter(x => x.triggered).map(x => x.id) }])),
    };
    this.probes.set(key, probe);
    this.stats.probes += 1;
    this.stats.probeMs += now() - started;
    return probe;
  }

  // ---------- Cores ----------
  // Sites sampled around the world origin by keyed hash; Chebyshev distance ≥ coreMinDistance to every placed core;
  // among RULES.coreCandidates valid sites the best terrain fit for that city wins. City order is fixed.
  generateCores() { return [...this.coreSteps()]; }

  // Same as generateCores, one core per iteration (the page yields a frame between cores).
  *coreSteps() {
    if (this.chunks.size) this.reset();
    const placed = [];
    for (const cityId of CITY_ORDER) {
      let spread = this.params.coreSpread;
      let sites = [];
      while (!sites.length) {
        for (let a = 0; a < RULES.coreAttempts && sites.length < RULES.coreCandidates; a += 1) {
          const angle = 2 * Math.PI * unit('core-angle', this.worldSeed, cityId, spread, a);
          const r = spread * Math.sqrt(unit('core-radius', this.worldSeed, cityId, spread, a));
          const gx = Math.round(r * Math.cos(angle)); const gy = Math.round(r * Math.sin(angle));
          if (placed.some(p => Math.max(Math.abs(p.gx - gx), Math.abs(p.gy - gy)) < this.params.coreMinDistance)) continue;
          if (sites.some(s => s.gx === gx && s.gy === gy)) continue;
          sites.push({ gx, gy, attempt: a });
        }
        if (!sites.length) {
          this.issues.push({ type: 'coreSpreadWidened', cityId, from: spread, to: spread + 2, reason: `no site ≥ ${this.params.coreMinDistance} chunks from the other cores within radius ${spread}` });
          spread += 2;
        }
      }
      const g = CITY_GROWTH[cityId];
      const scored = sites.map(s => {
        const p = this.probe(s.gx, s.gy);
        const fit = p.fit[cityId].fitScore;
        const usable = p.buildableFraction >= RULES.minBuildable;
        return { ...s, probe: p, fit, score: round((usable ? 1 : 0.2) * (0.7 * fit + 0.3 * g.landform[p.cell.landform])) };
      }).sort((a, b) => b.score - a.score || a.attempt - b.attempt);
      const best = scored[0];
      placed.push(best);
      const reason = { kind: 'core', score: best.score, candidates: scored.map(s => `${s.gx},${s.gy}:${s.probe.cell.landform}:${s.score}`), text: `core site ${best.gx},${best.gy} (${best.probe.cell.landform}) best of ${scored.length} sites, fit ${best.fit}, landform preference ${g.landform[best.probe.cell.landform]}` };
      const result = this.place(best.gx, best.gy, cityId, null, reason);
      this.cores.push(result.record.chunkId);
      yield result;
    }
  }

  // ---------- Frontier & scoring ----------
  // Unoccupied cells 4-adjacent to a chunk of the city, with the adjacent same-city chunks.
  frontier(cityId) {
    const cells = new Map();
    for (const r of this.chunks.values()) {
      if (r.cityId !== cityId) continue;
      const { gx, gy } = r.worldGridCoordinate;
      for (const [dx, dy, sideA] of NEIGHBOURS) {
        const nx = gx + dx; const ny = gy + dy;
        if (this.at(nx, ny)) continue;
        const key = cellKey(nx, ny);
        if (!cells.has(key)) cells.set(key, { gx: nx, gy: ny, key, adjacent: [] });
        cells.get(key).adjacent.push({ record: r, side: sideA });
      }
    }
    return [...cells.values()].sort(sortCells);
  }

  // Score of a frontier cell for one city at one step. Returns null terms + rejected reason for unusable cells.
  score(cityId, cand, step) {
    const p = this.probe(cand.gx, cand.gy);
    if (p.buildableFraction < RULES.minBuildable) return { score: -1, rejected: `buildable ${p.buildableFraction} < ${RULES.minBuildable} (water / cliff)`, probe: p };
    const g = CITY_GROWTH[cityId];
    const w = this.params;
    const ports = cand.adjacent.reduce((n, a) => n + a.record.ports[a.side].length, 0);
    const wf = p.waterFraction;
    const water = g.water >= 0 ? g.water * clamp01(wf / 0.25) + (1 - g.water) * (1 - clamp01(wf / 0.5)) : 1 + g.water * clamp01(wf / 0.3);
    const core = this.byId(cand.adjacent[0].record.coreChunkId).worldGridCoordinate;
    const dx = Math.abs(cand.gx - core.gx); const dy = Math.abs(cand.gy - core.gy);
    const axis = !g.axis || dx + dy === 0 ? 0.5 : (g.axis === 'x' ? dx : dy) / (dx + dy);
    const compactness = (cand.adjacent.length - 1) / 3;
    const dna = 0.6 * g.landform[p.cell.landform] + 0.2 * axis + 0.2 * (g.compact * compactness + (1 - g.compact) * 0.5);
    const terms = {
      terrain: round(p.fit[cityId].fitScore), slope: round(0.6 * clamp01(p.buildableFraction / 0.6) + 0.4 * p.lowSlope),
      roads: round(clamp01(ports / 3)), water: round(water), dna: round(dna),
    };
    const total = w.wTerrain + w.wSlope + w.wRoads + w.wWater + w.wDNA || 1;
    const base = (w.wTerrain * terms.terrain + w.wSlope * terms.slope + w.wRoads * terms.roads + w.wWater * terms.water + w.wDNA * terms.dna) / total;
    const jitter = w.jitter * (2 * unit('jitter', this.worldSeed, cityId, cand.gx, cand.gy, step) - 1);
    return { score: round(base + jitter, 4), base: round(base, 4), jitter: round(jitter, 4), terms, ports, probe: p };
  }

  // Fair scheduler: cities ordered by chunks / rate (fewest relative chunks first), ties by CITY_ORDER.
  schedule() {
    return [...CITY_ORDER].sort((a, b) => this.countOf(a) / CITY_GROWTH[a].rate - this.countOf(b) / CITY_GROWTH[b].rate || CITY_ORDER.indexOf(a) - CITY_ORDER.indexOf(b));
  }

  // Best legal move of one city at this step, or null with the reasons.
  bestMove(cityId, step) {
    const contests = [];
    const rejected = [];
    const options = [];
    const frontier = this.frontier(cityId);
    for (const cand of frontier) {
      const s = this.score(cityId, cand, step);
      if (s.rejected) { rejected.push({ cell: cand.key, reason: s.rejected }); continue; }
      // Contested: another city also touches this cell. A clearly stronger rival keeps it (deterministic, no overwrite).
      const rivals = CITY_ORDER.filter(id => id !== cityId && NEIGHBOURS.some(([dx, dy]) => this.at(cand.gx + dx, cand.gy + dy)?.cityId === id));
      if (rivals.length) {
        const rivalScores = rivals.map(id => {
          const adjacent = NEIGHBOURS.map(([dx, dy, , sideB]) => ({ record: this.at(cand.gx + dx, cand.gy + dy), side: sideB })).filter(a => a.record?.cityId === id);
          return { cityId: id, score: this.score(id, { ...cand, adjacent }, step).score };
        });
        const strongest = rivalScores.sort((a, b) => b.score - a.score)[0];
        const lost = strongest.score > s.score + RULES.contestMargin;
        contests.push({ cell: cand.key, claimant: cityId, claimantScore: s.score, rivals: rivalScores, outcome: lost ? `reserved for ${strongest.cityId}` : 'claimant keeps the claim' });
        if (lost) continue;
      }
      options.push({ cand, s });
    }
    options.sort((a, b) => b.s.score - a.s.score || sortCells(a.cand, b.cand));
    return { move: options[0] ?? null, frontierSize: frontier.length, contests, rejected, options: options.length };
  }

  // One growth step = exactly one new chunk (or a recorded stall if no city has a legal move).
  growStep() {
    if (!this.cores.length) throw new Error('Generate the six city cores first');
    const step = this.step + 1;
    const tried = [];
    for (const cityId of this.schedule()) {
      const result = this.bestMove(cityId, step);
      if (!result.move) { tried.push({ cityId, frontier: result.frontierSize, rejected: result.rejected.length, contests: result.contests.length }); continue; }
      const { cand, s } = result.move;
      // Parent: the adjacent same-city chunk with the most ports toward the cell, then the oldest.
      const parent = cand.adjacent.map(a => ({ a, n: a.record.ports[a.side].length })).sort((x, y) => y.n - x.n || x.a.record.generationIndex - y.a.record.generationIndex)[0].a;
      const top = Object.entries(s.terms).sort((a, b) => b[1] - a[1]).slice(0, 2).map(([k, v]) => `${k} ${v}`).join(', ');
      const reason = {
        kind: 'growth', score: s.score, base: s.base, jitter: s.jitter, terms: s.terms, portsTowardCell: s.ports,
        frontierSize: result.frontierSize, options: result.options, rejected: result.rejected.length, contests: result.contests,
        skippedCities: tried,
        text: `${cand.key} (${s.probe.cell.landform}) best of ${result.options} options for ${cityId}: score ${s.score} (${top}; jitter ${s.jitter >= 0 ? '+' : ''}${s.jitter})`,
      };
      this.step = step;
      return this.place(cand.gx, cand.gy, cityId, parent.record, reason);
    }
    this.step = step;
    const stall = { type: 'stalled', step, reason: 'no city has a legal frontier cell', cities: tried };
    this.issues.push(stall);
    return { stalled: stall };
  }

  growSteps(n) { const out = []; for (let i = 0; i < n; i += 1) { const r = this.growStep(); out.push(r); if (r.stalled) break; } return out; }

  // ---------- Placement ----------
  // Creates one immutable record: terrain + network of the cell, edge profiles / ports, shared-edge reports.
  place(gx, gy, cityId, parent, reason) {
    const key = cellKey(gx, gy);
    if (this.chunks.has(key)) throw new Error(`Cell ${key} is already occupied by ${this.chunks.get(key).chunkId}`);
    if (parent && Math.abs(parent.worldGridCoordinate.gx - gx) + Math.abs(parent.worldGridCoordinate.gy - gy) !== 1) throw new Error(`Parent ${parent.chunkId} is not edge-adjacent to ${key}`);
    const started = now();
    const cell = cellOf(this.worldSeed, gx, gy);
    const terrain = terrainOf(cell);
    const net = networkOf(cell, cityId, terrain);
    const sel = net.cityMatch.selectedDNA;
    const ports = { minX: [], maxX: [], minZ: [], maxZ: [] };
    for (const port of net.network.edgePorts) ports[port.side].push({ position: round(port.position, 1), type: port.type, roadClass: port.roadClass });
    const record = {
      chunkId: cell.chunkId, cityId, originCityId: parent ? parent.originCityId : cityId,
      coreChunkId: parent ? parent.coreChunkId : cell.chunkId, parentChunkId: parent ? parent.chunkId : null,
      worldGridCoordinate: { gx, gy }, worldOrigin: cell.worldOrigin, generationIndex: this.chunks.size, growthStep: this.step,
      terrainSeed: cell.terrainSeed, landform: cell.landform, variation: cell.variation,
      growthReason: reason,
      generationStatus: 'network', // lifecycle: network (data ready) → city → ready (rendered) | error
      suitability: { fitScore: sel.fitScore, weakFit: sel.weakFit, autoTopId: sel.autoTopId, conflicts: net.cityMatch.rankedCandidates.find(c => c.id === cityId).conflicts.filter(c => c.triggered).map(c => c.id) },
      ports,
      profiles: edgeProfiles(terrain.fields),
      signatures: { height: terrain.fields.stats.heightSignature, water: terrain.fields.stats.waterSignature, network: net.network.signature },
      depth: parent ? parent.depth + 1 : 0,
    };
    if (record.suitability.conflicts.length || sel.fitScore < RULES.weakFit) {
      this.issues.push({ type: 'suitability', chunkId: record.chunkId, cityId, landform: cell.landform, fitScore: sel.fitScore, autoTopId: sel.autoTopId, conflicts: record.suitability.conflicts, core: !parent, note: `City ID kept as specified (${parent ? 'inherited' : 'core'}); fitScore < ${RULES.weakFit} or a DNA conflict is triggered` });
    }
    this.chunks.set(key, Object.freeze(record));
    const edges = this.measureEdges(record);
    this.stats.buildMs += now() - started;
    this.history.push({ step: this.step, generationIndex: record.generationIndex, chunkId: record.chunkId, cityId, parentChunkId: record.parentChunkId, score: reason.score, contests: reason.contests?.length ?? 0, ms: Math.round(now() - started) });
    return { record, edges, transient: { cell, terrain, net } };
  }

  // Shared edges of a new chunk with every existing 4-neighbour. Geometry and identity are reported separately.
  measureEdges(b) {
    const out = [];
    const { gx, gy } = b.worldGridCoordinate;
    for (const [dx, dy, sideB, sideA] of NEIGHBOURS) {
      const a = this.at(gx + dx, gy + dy);
      if (!a) continue;
      const pa = a.profiles[sideA]; const pb = b.profiles[sideB];
      let max = 0; let sum = 0; let wet = 0;
      for (let i = 0; i < pa.h.length; i += 1) {
        const d = Math.abs(pa.h[i] - pb.h[i]); max = Math.max(max, d); sum += d;
        if (pa.w[i] !== pb.w[i]) wet += 1;
      }
      const portsA = a.ports[sideA]; const portsB = b.ports[sideB];
      const paired = portsA.filter(p => portsB.some(q => Math.abs(q.position - p.position) <= RULES.portTolerance && q.type === p.type)).length;
      const geometry = max <= RULES.seamContinuous ? 'continuous' : max <= RULES.seamStep ? 'step' : 'cliff';
      const report = {
        id: [a.chunkId, b.chunkId].join('|'), a: a.chunkId, b: b.chunkId, sideA, sideB,
        identity: a.cityId === b.cityId ? 'sameCity' : 'cityBoundary', cities: [a.cityId, b.cityId],
        geometry, maxDh: round(max, 2), meanDh: round(sum / pa.h.length, 2),
        hydrology: wet ? 'discontinuous' : 'continuous', wetMismatch: wet,
        transport: { portsA: portsA.length, portsB: portsB.length, pairedA: paired, unpaired: portsA.length + portsB.length - 2 * paired },
      };
      this.edges.set(report.id, report);
      out.push(report);
    }
    return out;
  }

  // ---------- Reports ----------
  summary() {
    const records = [...this.chunks.values()];
    const xs = records.map(r => r.worldGridCoordinate.gx); const ys = records.map(r => r.worldGridCoordinate.gy);
    const edges = [...this.edges.values()];
    const count = (list, f) => list.reduce((acc, item) => { const k = f(item); acc[k] = (acc[k] ?? 0) + 1; return acc; }, {});
    return {
      worldSeed: this.worldSeed, step: this.step, chunks: records.length,
      bounds: records.length ? { minX: Math.min(...xs), maxX: Math.max(...xs), minY: Math.min(...ys), maxY: Math.max(...ys) } : null,
      perCity: Object.fromEntries(CITY_ORDER.map(id => [id, this.countOf(id)])),
      landforms: count(records, r => r.landform),
      edges: { total: edges.length, identity: count(edges, e => e.identity), geometry: count(edges, e => e.geometry), hydrology: count(edges, e => e.hydrology), unpairedPorts: edges.reduce((n, e) => n + e.transport.unpaired, 0) },
      issues: this.issues.length,
    };
  }

  // ---------- Save / load ----------
  serialise() {
    return {
      version: GROWTH_VERSION, params: { ...this.params }, step: this.step, cores: [...this.cores],
      chunks: [...this.chunks.values()].sort((a, b) => a.generationIndex - b.generationIndex).map(r => ({ ...r, generationStatus: r.generationStatus })),
      edges: [...this.edges.values()], history: this.history, issues: this.issues,
    };
  }

  static restore(saved) {
    if (saved?.version !== GROWTH_VERSION) throw new Error(`Unsupported growth state version ${saved?.version}`);
    const c = new WorldGrowthController(saved.params);
    for (const r of saved.chunks) {
      const { gx, gy } = r.worldGridCoordinate;
      const cell = cellOf(c.worldSeed, gx, gy);
      if (cell.landform !== r.landform || cell.terrainSeed !== r.terrainSeed || cell.variation !== r.variation) throw new Error(`Saved cell ${r.chunkId} does not match the world rules (landform / seed / variation)`);
      if (!CITY_DNA[r.cityId]) throw new Error(`Unknown cityId ${r.cityId} at ${r.chunkId}`);
      if (c.chunks.has(cellKey(gx, gy))) throw new Error(`Duplicate cell ${r.chunkId} in saved state`);
      c.chunks.set(cellKey(gx, gy), Object.freeze({ ...r, generationStatus: 'network' }));
    }
    for (const e of saved.edges) c.edges.set(e.id, e);
    c.cores = [...saved.cores]; c.step = saved.step; c.history = [...saved.history]; c.issues = [...saved.issues];
    return c;
  }

  // Lifecycle update (render path): records stay frozen, so the status is replaced on a copy.
  setStatus(chunkId, status) {
    const r = this.byId(chunkId);
    const key = cellKey(r.worldGridCoordinate.gx, r.worldGridCoordinate.gy);
    this.chunks.set(key, Object.freeze({ ...r, generationStatus: status }));
  }
}
